create or replace function public.archive_month(p_year integer, p_month_index integer)
 returns integer
 language plpgsql
 set search_path to 'public'
as $function$
declare
  v_user uuid := auth.uid();
  v_start date := make_date(p_year, p_month_index + 1, 1);
  v_next date := (make_date(p_year, p_month_index + 1, 1) + interval '1 month')::date;
  v_count integer;
  v_completed timestamptz;
begin
  if v_user is null then
    raise exception 'Vous devez ├¬tre connect├®.';
  end if;
  if p_month_index < 0 or p_month_index > 11 then
    raise exception 'Mois invalide.';
  end if;
  if exists (select 1 from archived_months where user_id = v_user and year = p_year and month_index = p_month_index) then
    raise exception 'Ce mois est d├®j├á archiv├®.';
  end if;

  select count(*), max(reconciled_at) into v_count, v_completed
  from transactions
  where user_id = v_user and booked_on >= v_start and booked_on < v_next;

  if v_count = 0 then
    raise exception 'Aucune op├®ration ├á archiver ce mois-ci.';
  end if;
  if exists (select 1 from transactions where user_id = v_user and booked_on >= v_start and booked_on < v_next and reconciled_at is null) then
    raise exception 'Pointe dÔÇÖabord toutes les op├®rations du mois.';
  end if;
  if exists (select 1 from transactions where user_id = v_user and booked_on >= v_start and booked_on < v_next and category_id is null) then
    raise exception 'Cat├®gorise dÔÇÖabord toutes les op├®rations du mois.';
  end if;

  insert into monthly_actuals (user_id, year, month_index, category_id, amount, operations_count)
  select v_user, p_year, p_month_index, category_id, sum(amount), count(*)
  from transactions
  where user_id = v_user and booked_on >= v_start and booked_on < v_next
  group by category_id;

  insert into archived_months (user_id, year, month_index, operations_count, completed_at)
  values (v_user, p_year, p_month_index, v_count, v_completed);

  delete from transactions
  where user_id = v_user and booked_on >= v_start and booked_on < v_next;

  return v_count;
end;
$function$;

create or replace function public.budget_overruns_due()
 returns table(subscription_id uuid, user_id uuid, endpoint text, p256dh text, auth text, overrun_count bigint, month_key text)
 language sql
 stable
 set search_path to 'public'
as $function$
  with cur as (
    select
      extract(year from (now() at time zone 'Europe/Paris'))::int as y,
      extract(month from (now() at time zone 'Europe/Paris'))::int - 1 as m,
      to_char(now() at time zone 'Europe/Paris', 'YYYY-MM') as key,
      date_trunc('month', now() at time zone 'Europe/Paris')::date as start_d,
      (date_trunc('month', now() at time zone 'Europe/Paris') + interval '1 month')::date as next_d
  ),
  budgets as (
    select b.user_id, b.category_id, sum(b.amount) as budget
    from budget_entries b, cur
    where b.year = cur.y and b.month_index = cur.m
    group by b.user_id, b.category_id
    having sum(b.amount) > 0
  ),
  spent as (
    select t.user_id, t.category_id, sum(-t.amount) as spent
    from transactions t, cur
    where t.amount < 0
      and t.category_id is not null
      and t.booked_on >= cur.start_d
      and t.booked_on < cur.next_d
    group by t.user_id, t.category_id
  ),
  over as (
    select b.user_id, count(*) as n
    from budgets b
    join spent s on s.user_id = b.user_id and s.category_id = b.category_id
    where s.spent > b.budget
    group by b.user_id
  )
  select s.id, s.user_id, s.endpoint, s.p256dh, s.auth, o.n, cur.key
  from push_subscriptions s
  join over o on o.user_id = s.user_id
  cross join cur
  left join user_settings us on us.user_id = s.user_id
  where coalesce(us.notify_budget_overrun, true)
    and (s.overrun_alerted_month is distinct from cur.key or o.n > s.overrun_alerted_count);
$function$;

